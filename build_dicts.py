"""Builds the extra dictionary data files from SWORD modules (crosswire.org):

  Condensed Biblical Cyclopedia (CBC, public domain)    -> data/cbc.js
  International Standard Bible Encyclopedia (ISBE, PD)  -> data/isbe.js  (complete: every article, uncut)
  Webster's 1828 Dictionary (CC BY-SA 4.0)              -> data/webster1828.js
  Webster's 1913 Unabridged Dictionary (PD)             -> data/webster1913.js

Output: window.<NAME>_DICTIONARY = {lowercased key: {name, text}}, the shape
easton.js's lookup engine uses (see dicts.js).

The ISBE is kept COMPLETE (all ~9,400 articles, no cutting, ~25 MB; the app
loads it lazily and formats long articles only when opened). Webster 1828 (24 MB)
and 1913 (78 MB) are too large to ship whole, so they are reduced to what the
study panel can use: only headwords that occur in the KJV, without the most
frequent function words, and long entries are cut at a sentence boundary
(Webster 1828 2500 chars, Webster 1913 1800).

Webster 1828 is CC BY-SA 4.0: keep the attribution and share-alike if you
redistribute this data.

Run: python build_dicts.py   (downloads the modules)
"""
import collections, html, json, os, re, sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import build_topics as bt

DATA = bt.DATA
STOP_TOP = 150  # drop the N most frequent KJV words (the, and, of, unto, ...)


def kjv_vocab():
    txt = open(os.path.join(DATA, "bible_kjv.js"), encoding="utf-8").read()
    books = json.loads(txt[txt.index("["):txt.rindex("]") + 1])
    freq = collections.Counter()
    for b in books:
        for ch in b["chapters"]:
            for v in ch or []:
                freq.update(w.strip("'") for w in re.findall(r"[a-z']+", v.lower()) if w.strip("'"))
    stop = {w for w, _ in freq.most_common(STOP_TOP)}
    return set(freq) - stop, freq


def cut(text, cap):
    if len(text) <= cap:
        return text
    cut_at = max(text.rfind(". ", 0, cap), text.rfind("\n", 0, cap))
    if cut_at < cap * 0.5:
        cut_at = cap
    return text[:cut_at + 1].rstrip() + " …"


def plain(body):
    t = body.replace("\x00", "").replace("�", "")
    t = re.sub(r"<br\s*/?>|<lb\s*/>", "\n", t)
    t = re.sub(r"</?(p|li)[^>]*>", "\n", t)
    t = re.sub(r"<[^>]+>", "", t)
    t = html.unescape(t).replace("\xa0", " ")
    t = re.sub(r"[ \t]+", " ", t)
    t = re.sub(r" *\n *", "\n", t)
    return re.sub(r"\n{2,}", "\n\n", t).strip()


def keys_for(name):
    """Lookup keys for a headword: the full name, the part before a comma and
    without a "(2)"-style homograph suffix."""
    base = re.sub(r"\s*\(\d+\)\s*$", "", name.strip())
    keys = [base.lower()]
    first = re.split(r"[,(]", base)[0].strip().lower()
    if first and first not in keys:
        keys.append(first)
    return [k for k in keys if len(k) >= 3]


def build(entries, vocab, cap, drop_stop, header_strip=None):
    out = {}
    secondary = set()
    for name, body in entries:
        if not name:
            continue
        keys = keys_for(name)
        if vocab is not None:
            ok = []
            for k in keys:
                words = [w.strip("'") for w in re.findall(r"[a-z']+", k)]
                if words and (all(w in vocab for w in words) if len(words) > 1 else words[0] in vocab):
                    ok.append(k)
            keys = ok
        elif drop_stop:
            keys = [k for k in keys]
        if not keys:
            continue
        text = plain(body)
        if header_strip:
            text = header_strip(text)
        if not text:
            continue
        label = bt.nice_name(re.sub(r"\s*\(\d+\)\s*$", "", name.strip()))
        for i, k in enumerate(keys):
            primary = i == 0
            e = out.get(k)
            if e is None:
                out[k] = {"name": label if primary else bt.nice_name(k), "text": text}
                if not primary:
                    secondary.add(k)
            elif primary and k in secondary:  # a real headword beats a shortened one
                out[k] = {"name": label, "text": text}
                secondary.discard(k)
            elif primary and (not cap or len(e["text"]) < cap):  # homographs share one entry
                e["text"] += "\n\n" + text
    if cap:
        for e in out.values():
            e["text"] = cut(e["text"], cap)
    return out


def write(fname, glob, label, entries):
    path = os.path.join(DATA, fname)
    with open(path, "w", encoding="utf-8") as f:
        f.write("// Generated by build_dicts.py -- %s.\n" % label)
        f.write("window.%s=" % glob + json.dumps(entries, ensure_ascii=False, separators=(",", ":")) + ";\n")
    print(fname, len(entries), "entries", os.path.getsize(path), "bytes")


def main():
    vocab, _ = kjv_vocab()
    print("KJV vocabulary (minus top %d): %d words" % (STOP_TOP, len(vocab)))

    z = bt.fetch("CBC")
    write("cbc.js", "CBC_DICTIONARY", "Condensed Biblical Cyclopedia (public domain)",
          build(bt.read_rawld(z, "modules/lexdict/rawld/cbc/cbc", "cp1252"), None, 60000, False))

    z = bt.fetch("ISBE")
    write("isbe.js", "ISBE_DICTIONARY", "International Standard Bible Encyclopedia (public domain)",
          build(bt.read_zld(z, "modules/lexdict/zld/isbe/isbe"), None, None, False))

    z = bt.fetch("Webster1828")
    write("webster1828.js", "WEBSTER1828_DICTIONARY", "Webster's 1828 Dictionary (CC BY-SA 4.0)",
          build(bt.read_zld(z, "modules/lexdict/zld/webster1828/dict"), vocab, 2500, True))

    z = bt.fetch("Webster1913")
    write("webster1913.js", "WEBSTER1913_DICTIONARY", "Webster's 1913 Unabridged Dictionary (public domain)",
          build(bt.read_zld(z, "modules/lexdict/zld/webster1913/webster1913"), vocab, 1800, True))


if __name__ == "__main__":
    main()
