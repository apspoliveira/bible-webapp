"""Builds data/smith.js from the public-domain SWORD module "Smith"
(Smith's Bible Dictionary, William Smith, 1884).

Output: window.SMITH_DICTIONARY = {lowercased headword: {name, text}}, the same
shape as Easton's (data/easton.js), so easton.js can reuse its lookup engine.
Scripture references are rewritten to the compact form the app's reference
linker understands ("Ge 8:4"), taken from each <scripRef passage="..."> attribute.

Run: python build_smith.py   (downloads the module from crosswire.org)
"""
import io, json, os, re, struct, urllib.request, zipfile

URL = "https://crosswire.org/ftpmirror/pub/sword/packages/rawzip/Smith.zip"
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "data", "smith.js")


def to_plain(body):
    body = body.replace("\r\n", "\n").replace("\xa0", " ")
    # <scripRef passage="2ki 19:37">2 Kings 19:37</scripRef> -> "2Ki 19:37"
    def passage(m):
        p = m.group(1).strip()
        mm = re.match(r"^([1-3]?)\s*([a-z]+)\s+(.*)$", p)
        if not mm:
            return m.group(2)
        return "%s%s %s" % (mm.group(1), mm.group(2).capitalize(), mm.group(3))
    body = re.sub(r'<scripRef passage="([^"]*)">(.*?)</scripRef>', passage, body, flags=re.S)
    body = re.sub(r"<li[^>]*>", "\n• ", body)
    body = re.sub(r"</?(ol|ul|i|b|term|p|br)\s*/?>", "", body)
    body = re.sub(r"<[^>]+>", "", body)
    body = re.sub(r"[ \t]+\n", "\n", body)
    body = re.sub(r"\n{3,}", "\n\n", body)
    return body.strip()


def main():
    z = zipfile.ZipFile(io.BytesIO(urllib.request.urlopen(URL).read()))
    idx = z.read("modules/lexdict/rawld/smith/smith.idx")
    dat = z.read("modules/lexdict/rawld/smith/smith.dat")
    entries = {}
    for i in range(len(idx) // 6):
        o, s = struct.unpack("<IH", idx[i * 6:i * 6 + 6])
        raw = dat[o:o + s].decode("cp1252", "replace")
        head, _, body = raw.partition("\n")
        head = head.strip()
        if len(head) < 3:
            continue
        key = head.lower()
        text = to_plain(body)
        if not text:
            continue
        name = head.title() if head.isupper() else head
        if key in entries:  # homonyms (e.g. two people with one name): keep both
            entries[key]["text"] += "\n\n" + text
        else:
            entries[key] = {"name": name, "text": text}
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("// Generated by build_smith.py -- Smith's Bible Dictionary (public domain).\n")
        f.write("window.SMITH_DICTIONARY=" + json.dumps(entries, ensure_ascii=False, separators=(",", ":")) + ";\n")
    print(len(entries), "entries,", os.path.getsize(OUT), "bytes")


main()
